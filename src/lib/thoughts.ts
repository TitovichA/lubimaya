export function createThoughtsSeed(): Thought[] {
  return DEFAULT_THOUGHTS.map((text, i) => ({
    id: `th-${i + 1}`,
    text,
    favorite: false,
    order: i,
  }))
}

export function pickThoughtForDate(
  thoughts: Thought[],
  thoughtByDate: Record<string, string>,
  cycleShown: string[],
  date: string,
): { thought: Thought | null; thoughtByDate: Record<string, string>; cycleShown: string[] } {
  if (!thoughts.length) {
    return { thought: null, thoughtByDate, cycleShown }
  }

  const existingId = thoughtByDate[date]
  if (existingId) {
    const found = thoughts.find((t) => t.id === existingId)
    if (found) return { thought: found, thoughtByDate, cycleShown }
  }

  const sorted = [...thoughts].sort((a, b) => a.order - b.order)
  let shown = [...cycleShown]
  let available = sorted.filter((t) => !shown.includes(t.id))
  if (!available.length) {
    shown = []
    available = sorted
  }

  const pick = available[Math.floor(Math.random() * available.length)]
  return {
    thought: pick,
    thoughtByDate: { ...thoughtByDate, [date]: pick.id },
    cycleShown: [...shown, pick.id],
  }
}
